def transliterate_unseen_word(word: str, lang_code: str) -> str:
    """Transliterate an unseen Latin word phonetically into native target script."""
    clean = word.lower()
    if not any("a" <= ch <= "z" for ch in clean):
        return word

    if lang_code == "ur":
        out = []
        i = 0
        while i < len(clean):
            matched = False
            for pat, rep in URDU_CHAR_MAP:
                if clean.startswith(pat, i):
                    out.append(rep)
                    i += len(pat)
                    matched = True
                    break
            if not matched:
                out.append(clean[i])
                i += 1
        return "".join(out)

    # First produce clean Devanagari syllables
    dev = []
    i = 0
    while i < len(clean):
        if i == 0:
            v_hit = False
            for pat, rep in DEV_VOWELS_INIT:
                if clean.startswith(pat, i):
                    dev.append(rep)
                    i += len(pat)
                    v_hit = True
                    break
            if v_hit:
                continue
        c_hit = False
        for pat, rep in DEV_CONSONANTS:
            if clean.startswith(pat, i):
                dev.append(rep)
                i += len(pat)
                m_hit = False
                for mpat, mrep in DEV_VOWELS_MATRA:
                    if clean.startswith(mpat, i):
                        dev.append(mrep)
                        i += len(mpat)
                        m_hit = True
                        break
                if not m_hit and i < len(clean):
                    dev.append("्")
                c_hit = True
                break
        if c_hit:
            continue
        for pat, rep in DEV_VOWELS_INIT:
            if clean.startswith(pat, i):
                dev.append(rep)
                i += len(pat)
                c_hit = True
                break
        if not c_hit:
            dev.append(clean[i])
            i += 1

    dev_str = "".join(dev)
    offset = BRAHMIC_OFFSETS.get(lang_code, 0)
    if offset == 0:
        return dev_str

    # Shift Devanagari codepoints cleanly into target Brahmic block
    mapped_chars = []
    for ch in dev_str:
        cp = ord(ch)
        if 0x0901 <= cp <= 0x0939 or 0x093E <= cp <= 0x094D:
            target_cp = cp + offset
            # Tamil fallback for aspirated/voiced plosives without distinct glyphs in Unicode Tamil block
            if lang_code == "ta":
                dev_to_ta = {
                    "ख": "க", "ग": "க", "घ": "க",
                    "छ": "ச", "ज": "ஜ", "झ": "ஜ",
                    "ठ": "ட", "ड": "ட", "ढ": "ட",
                    "थ": "த", "द": "த", "ध": "த",
                    "फ": "ப", "ब": "ப", "भ": "ப",
                    "श": "ஶ",
                }
                if ch in dev_to_ta:
                    mapped_chars.append(dev_to_ta[ch])
                    continue
            mapped_chars.append(chr(target_cp))
        else:
            mapped_chars.append(ch)
    return "".join(mapped_chars)


def _lookup_word(word: str, lang_code: str) -> str:
    idx = LANG_IDX[lang_code]
    lw = word.lower()
    if lw in LEXICON:
        return LEXICON[lw][idx]
    # Singular fallback
    if lw.endswith("s") and lw[:-1] in LEXICON:
        return LEXICON[lw[:-1]][idx]
    return transliterate_unseen_word(lw, lang_code)


def _translate_clause_indic(clause: str, lang_code: str) -> str:
    idx = LANG_IDX[lang_code]
    s = clause.strip()
    if not s:
        return ""

    punct = "."
    if s[-1] in "?!.":
        punct = s[-1]
        s = s[:-1].strip()
    target_punct = SENTENCE_PUNCT[lang_code].get(punct, punct)

    # Check leading greeting prefix ("Hello, how are you?", "Good morning, Mother!", "Thank you, Doctor!")
    low_full = s.lower()
    if low_full in GREETING_PHRASES:
        return GREETING_PHRASES[low_full][idx] + target_punct

    for g_key in ("good morning", "good afternoon", "good evening", "good night", "thank you", "hello"):
        if low_full.startswith(g_key):
            rest = s[len(g_key):].lstrip(", ").strip()
            g_native = GREETING_PHRASES[g_key][idx]
            if not rest:
                return g_native + target_punct
            rest_native = _translate_clause_indic(rest + punct, lang_code)
            return f"{g_native}, {rest_native}"

    # Tokenize English words
    raw_words = [w.strip(",;:\"'()") for w in s.split() if w.strip(",;:\"'()")]
    if not raw_words:
        return ""

    # Single word
    if len(raw_words) == 1:
        return _lookup_word(raw_words[0], lang_code) + (target_punct if punct in "?!" else "")

    low = [w.lower() for w in raw_words]

    # Detect polarity, tense, question word, verb, subject, object/modifiers
    negated = False
    tense = "pres"
    wh = None
    is_yesno_q = (punct == "?") and (low[0] in {"am", "is", "are", "was", "were", "do", "does", "did", "will", "can"})

    VERB_MAP = {
        "go": "go", "goes": "go", "going": "go", "went": "go",
        "come": "come", "comes": "come", "coming": "come", "came": "come",
        "read": "read", "reads": "read", "reading": "read",
        "write": "write", "writes": "write", "writing": "write", "wrote": "write",
        "drive": "drive", "drives": "drive", "driving": "drive", "drove": "drive",
        "eat": "eat", "eats": "eat", "eating": "eat", "ate": "eat",
        "drink": "drink", "drinks": "drink", "drinking": "drink", "drank": "drink",
        "have": "have", "has": "have", "had": "have",
        "need": "need", "needs": "need",
        "want": "want", "wants": "want",
        "help": "help", "helps": "help", "helping": "help",
    }

    DROP_AUX = {"am", "is", "are", "was", "were", "be", "a", "an", "the", "to", "in", "at", "on", "of", "do", "does", "did", "will"}
    TIME_SET = {"today", "tomorrow", "yesterday", "now", "morning", "afternoon", "evening", "night"}
    WH_SET = {"what", "where", "when", "who", "why", "which", "how"}

    if "tomorrow" in low or "will" in low or "won't" in low:
        tense = "fut"
    elif "yesterday" in low or "did" in low or "was" in low or "were" in low or any(x in {"went", "came", "wrote", "drove", "ate", "drank"} for x in low):
        tense = "past"

    time_terms = []
    content_terms = []
    verb_key = None

    for w in raw_words:
        wl = w.lower()
        if wl in {"not", "no", "never", "don't", "doesn't", "didn't", "won't", "isn't", "aren't", "can't", "cannot"}:
            negated = True
            if wl == "won't":
                tense = "fut"
            continue
        if wl in WH_SET and wh is None:
            wh = wl
            continue
        if wl in TIME_SET:
            time_terms.append(_lookup_word(wl, lang_code))
            continue
        if wl in VERB_MAP and verb_key is None:
            verb_key = VERB_MAP[wl]
            continue
        if wl in DROP_AUX:
            continue
        content_terms.append(wl)

    # Separate Subject from Predicate/Object in SVO English clause
    subj_words = []
    pred_words = []
    if content_terms:
        if len(content_terms) >= 2 and content_terms[0] in {"my", "your", "our", "his", "her", "their"}:
            subj_words = content_terms[:2]
            pred_words = content_terms[2:]
        elif len(content_terms) >= 3 and content_terms[1] == "and":
            subj_words = content_terms[:3]
            pred_words = content_terms[3:]
        else:
            subj_words = content_terms[:1]
            pred_words = content_terms[1:]

    subj_native = " ".join(_lookup_word(x, lang_code) for x in subj_words)
    pred_native = " ".join(_lookup_word(x, lang_code) for x in pred_words)
    wh_native = _lookup_word(wh, lang_code) if wh else ""
    yesno_lead = (_lookup_word("what", lang_code) + " ") if (is_yesno_q and not wh_native and lang_code in {"hi", "mr", "ur"}) else ""

    # Realize verb phrase in authentic Indian SOV order:
    # [Yes/No Q] + [Time] + [Subject] + [Object/Location] + [Interrogative] + [Verb/Copula]
    is_1sg = subj_words == ["i"]
    is_2pl = subj_words in (["you"], ["we"], ["they"]) or ("and" in subj_words)

    if verb_key is not None:
        vtable = VERB_FORMS[verb_key]
        if verb_key in {"have", "need"} and len(subj_words) == 1:
            # Ergative/oblique possessor in Hindi/Marathi/Gujarati/Urdu/Kannada/Tamil/Telugu/Malayalam
            subj_base = _lookup_word(subj_words[0], lang_code)
            v_str = vtable["neg"][idx] if negated else vtable["pres"][idx]
            mid = " ".join(p for p in [wh_native, pred_native] if p)
            pieces = time_terms + [subj_base, mid, v_str]
        else:
            if negated:
                v_str = vtable.get("neg_fut", vtable["neg"])[idx] if tense == "fut" else vtable["neg"][idx]
            elif tense == "fut":
                v_str = vtable.get("fut" if is_1sg else "fut3", vtable.get("fut", vtable["pres"]))[idx]
            elif tense == "past":
                v_str = vtable.get("past", vtable["pres"])[idx]
            else:
                v_str = vtable.get("pres" if is_1sg else "pres3", vtable["pres"])[idx]
            pieces = ([yesno_lead.strip()] if yesno_lead.strip() else []) + time_terms + [subj_native, pred_native, wh_native, v_str]
    else:
        if negated:
            cop = (COPULA_NEG_1SG if is_1sg else COPULA_NEG)[idx]
        else:
            cop = (COPULA_POS_1SG if is_1sg else (COPULA_POS_2PL if is_2pl else COPULA_POS))[idx]
        pieces = ([yesno_lead.strip()] if yesno_lead.strip() else []) + time_terms + [subj_native, pred_native, wh_native, cop]

    assembled = re.sub(r"\s+", " ", " ".join(p for p in pieces if p)).strip()
    return assembled + target_punct


def translate_english_to_indic(english_text: str, lang_code: str) -> str:
    """
    Translate a well-formed English sentence (or multi-sentence paragraph) into
    any of the 8 supported Indian languages in authentic native script and SOV grammar.
    """
    if lang_code not in LANG_IDX:
        raise ValueError(f"Unsupported Indic language code: {lang_code}")

    clauses = re.findall(r"[^.!?]+[.!?]?", english_text)
    outputs = []
    for cl in clauses:
        cl = cl.strip()
        if not cl:
            continue
        rendered = _translate_clause_indic(cl, lang_code)
        if rendered:
            outputs.append(rendered)
    return " ".join(outputs)
